const { chromium } = require('playwright');
const { pathToFileURL } = require('node:url');
const path = require('node:path');
const os = require('node:os');
const assert = require('node:assert/strict');
(async () => {
  const browser = await chromium.launch({ channel: process.env.TEST_BROWSER || 'chrome', headless: true });
  const page = await browser.newPage({ viewport: { width: 794, height: 1123 } });
  await page.goto(pathToFileURL(path.resolve(__dirname, '../index.html')).href);
  await page.evaluate(() => localStorage.clear());
  await page.reload();
  const codes = Array.from({ length: 20 }, (_, i) => `PROD${String(i + 1).padStart(3, '0')}`).join('\n');
  await page.locator('#input').fill(codes);
  await page.locator('#generate').click();
  assert.equal(await page.locator('.quantity, .qr-details p').count(), 0);
  await page.emulateMedia({ media: 'print' });
  assert.equal(await page.locator('.qr-header').first().isVisible(), false);
  for (const selector of ['.original-header', '.control-panel', '.preview-toolbar', '.print-bar', 'footer']) {
    assert.equal(await page.locator(selector).isVisible(), false, selector);
  }
  const columns = await page.locator('.qr-grid').evaluate((el) => getComputedStyle(el).gridTemplateColumns.split(' ').length);
  assert.equal(columns, 4);
  const card = await page.locator('.qr-card').first().boundingBox();
  assert.ok(card.height < 180, `Etiqueta sem campos extras: ${card.height}px`);
  await page.locator('.qr-grid').screenshot({ path: path.join(os.tmpdir(), 'qrgen-compact-print.png') });
  await page.pdf({ path: path.join(os.tmpdir(), 'qrgen-compact-print.pdf'), preferCSSPageSize: true });
  await page.emulateMedia({ media: 'screen' });
  await page.locator('[data-view="table"]').click();
  await page.emulateMedia({ media: 'print' });
  assert.equal(await page.locator('th.quantity-column').isVisible(), false);
  assert.equal(await page.locator('td.quantity-column').first().isVisible(), false);
  await page.emulateMedia({ media: 'screen' });
  await page.locator('[data-view="economic"]').click();
  await page.emulateMedia({ media: 'print' });
  assert.equal(await page.locator('.qr-grid').evaluate((el) => getComputedStyle(el).gridTemplateColumns.split(' ').length), 8);
  assert.equal(await page.locator('.quantity').count(), 0);
  await page.emulateMedia({ media: 'screen' });
  await page.locator('[data-view="cards"]').click();
  await page.locator('.type-switch [data-type="barcode"]').click();
  await page.locator('#input').fill('ABC001;;\nABC002;Com quantidade;0');
  await page.locator('#generate').click();
  assert.equal(await page.locator('.quantity').count(), 1);
  assert.equal(await page.locator('.quantity').innerText(), 'Qtd: 0');
  await page.emulateMedia({ media: 'print' });
  assert.equal(await page.locator('.qr-grid').evaluate((el) => getComputedStyle(el).gridTemplateColumns.split(' ').length), 2);
  assert.equal(await page.locator('.qr-details h3').first().isVisible(), false);
  assert.equal(await page.locator('.qrbox svg').first().isVisible(), true);
  await page.emulateMedia({ media: 'screen' });
  await page.locator('[data-view="economic"]').click();
  await page.emulateMedia({ media: 'print' });
  assert.equal(await page.locator('.qr-grid').evaluate((el) => getComputedStyle(el).gridTemplateColumns.split(' ').length), 3);
  await browser.close();
  console.log('PASS: impressão compacta, campos vazios omitidos, quantidade zero preservada, 4/8 colunas QR, 2 colunas barras, 3 no econômico e interface oculta.');
})().catch((error) => { console.error(error); process.exit(1); });
